/**
 * Fallback helpers
 */
export function getFallbackAlbumsResponse(page = 1, perPage = 20): TrimmedAlbumsResponse {
  const start = (page - 1) * perPage;
  const paginated = FALLBACK_ALBUMS.slice(start, start + perPage);

  return {
    total: FALLBACK_ALBUMS.length,
    page,
    perPage,
    pages: Math.ceil(FALLBACK_ALBUMS.length / perPage) || 1,
    albums: paginated.map((a) => ({
      id: a.id,
      title: a.title,
      description: a.description,
      photoCount: a.photoCount,
      coverImageUrl: a.coverImageUrl,
      dateCreated: a.dateCreated,
    })),
  };
}

export function getFallbackAlbumPhotosResponse(albumId: string, page = 1, perPage = 20): TrimmedAlbumPhotosResponse | null {
  const album = FALLBACK_ALBUMS.find((a) => a.id === albumId);
  if (!album) return null;

  const start = (page - 1) * perPage;
  const paginated = album.photos.slice(start, start + perPage);

  return {
    albumId: album.id,
    title: album.title,
    total: album.photos.length,
    page,
    perPage,
    pages: Math.ceil(album.photos.length / perPage) || 1,
    photos: paginated,
  };
}
